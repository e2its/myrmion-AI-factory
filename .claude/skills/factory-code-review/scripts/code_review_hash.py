#!/usr/bin/env python3
"""code_review_hash.py — canonical RDR-1 content hash for the Block 20 marker.

Generated by Phase: [EVOL] | Feature: [EVOL-039]

Reads detect_change_type.py JSON on stdin, filters the `files` dict to
`is_code OR is_test` paths (tests included: pr-test-analyzer reviews them),
drops paths deleted at HEAD, and prints
    sha256("\n".join(sorted(f"{path}\\0{git blob sha at HEAD}")))
as 64-hex. Empty reviewable set -> prints "EMPTY", exit 0.

Both the factory-code-review branch pass (marker writer) and preflight.sh
Step 0-bis (marker verifier) run the SAME pipeline:
    detect_change_type.py --git-range BASE..HEAD [--check-secrets] | code_review_hash.py
so the hash is identical by construction. Extra JSON keys are ignored.

Presence of this file doubles as the RDR-2 executor-presence probe consumed
by preflight.sh Step 0-bis (absent -> noisy warning, push passes).

Exit codes: 0 ok (hash or EMPTY on stdout), 2 tooling failure (bad stdin,
git unavailable) — NEVER 1; findings are not this script's concern.
"""

import json
import hashlib
import subprocess
import sys


def blob_sha(path: str) -> str | None:
    """Git blob sha of path at HEAD; None when absent (deleted/renamed away)."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", f"HEAD:{path}"],
            capture_output=True, text=True, timeout=10,
        )
    except Exception:
        return None
    if out.returncode != 0:
        return None
    return out.stdout.strip()


def main() -> int:
    try:
        classification = json.load(sys.stdin)
    except Exception:
        print("code_review_hash: cannot parse detect_change_type.py JSON on stdin", file=sys.stderr)
        return 2

    files = classification.get("files", {})
    if not isinstance(files, dict):
        print("code_review_hash: 'files' key missing or malformed", file=sys.stderr)
        return 2

    reviewable = sorted(
        p for p, c in files.items()
        if isinstance(c, dict) and (c.get("is_code") or c.get("is_test"))
    )

    entries = []
    for path in reviewable:
        sha = blob_sha(path)
        if sha is None:
            continue  # deleted at HEAD — nothing to review
        entries.append(f"{path}\0{sha}")

    if not entries:
        print("EMPTY")
        return 0

    digest = hashlib.sha256("\n".join(entries).encode("utf-8")).hexdigest()
    print(digest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
